def test_installs_from_requirements_file(deploy, testwf):
    for wf in (deploy, testwf):
        runs = "\n".join(s for _, s in run_scripts(wf))
        assert re.search(r"pip install -r requirements(-dev)?\.txt", runs)
        assert not re.search(r"pip install\s+(?!-r)\S+==", runs)
        for _, step in all_steps(wf):
            if str(step.get("uses", "")).startswith("actions/setup-python"):
                assert step["with"]["cache"] == "pip"
                assert "requirements" in step["with"]["cache-dependency-path"]


def test_changed_files_not_interpolated_into_shell(deploy):
    for job, run in run_scripts(deploy):
        assert "${{" not in run, f"{job}: expression interpolated into run script"
        assert "CHANGED_FILES" not in run
    # file lists travel NUL-delimited in files and are consumed by scripts/ci_*.sh
    for name in ("ci_validate.sh", "ci_heal.sh", "ci_deploy.sh"):
        sh = script(name)
        assert "IFS= read -r -d ''" in sh, name
        assert "eval " not in sh and not re.search(r"for\s+\w+\s+in\s+\$", sh), name
    assert not re.search(r"for\s+\w+\s+in\s+\$", DEPLOY.read_text(encoding="utf-8"))
    for name in ("ci_validate.sh", "ci_heal.sh", "ci_push.sh", "ci_deploy.sh"):
        assert (SCRIPTS / name).is_file()
        assert any(f"scripts/{name}" in s for _, s in run_scripts(deploy)), name


def test_checkout_has_full_history_and_diff_uses_after_sha(deploy):
    for job_name, job in deploy["jobs"].items():
        co = [s for s in job["steps"] if str(s.get("uses", "")).startswith("actions/checkout")]
        assert co and co[0]["with"]["fetch-depth"] == 0, job_name
    plans = [s for _, s in all_steps(deploy) if s.get("name") == PLAN_STEP]
    assert len(plans) == 2
    for s in plans:
        assert s["env"]["AFTER_SHA"] == "${{ github.sha }}"
        assert '--after "$AFTER_SHA"' in s["run"]
        assert "HEAD~1" not in s["run"]
    assert "--diff-filter=ACMR" not in DEPLOY.read_text(encoding="utf-8")


def test_deploy_script_supports_deletion_and_retag():
    sh = script("ci_deploy.sh")
    assert "--delete" in sh and "--allow-retag" in sh
    step = next(s for _, s in all_steps(load(DEPLOY)) if "ci_deploy.sh" in s.get("run", ""))
    assert {"ELASTIC_URL", "KIBANA_URL", "ELASTIC_API_KEY"} <= set(step["env"])


def test_heal_tags_new_rules_and_cannot_retrigger_the_workflow(deploy):
    heal = script("ci_heal.sh")
    assert "tools/tag_compliance.py --write --files" in heal
    # (1) [skip ci] in the commit message; (2) the push uses GITHUB_TOKEN, which GitHub never uses to
    # start workflow runs. Either alone prevents a loop; a PAT would still be covered by (1).
    assert re.search(r'-m "[^"]*\[skip ci\]"', heal)
    push_step = next(s for _, s in all_steps(deploy) if s.get("name") == PUSH_STEP)
    assert "github.token" in push_step["env"]["GH_TOKEN"]
    assert push_step["if"] == "steps.heal.outputs.committed == 'true'"


def test_push_failure_is_not_swallowed():
    sh = script("ci_push.sh")
    assert "pull --rebase" in sh and "rebase --abort" in sh
    assert sh.count("exit 1") >= 2
    assert "|| true" not in sh.replace("rebase --abort 2>/dev/null || true", "")
    assert "branch protection" in sh


def test_third_party_actions_pinned_by_sha(deploy, testwf):
    known = {
        "actions/checkout": "11bd71901bbe5b1630ceea73d27597364c9af683",
        "actions/setup-python": "a26af69be951a213d495a4c3e4e4022e16d87065",
    }
    for wf in (deploy, testwf):
        for _, step in all_steps(wf):
            if "uses" in step:
                assert SHA_RE.match(step["uses"]), step["uses"]
                name, sha = step["uses"].split("@")
                assert known.get(name) == sha, step["uses"]


def test_deploy_env_matches_script_configuration(deploy):
    env_names = set()
    for job in deploy["jobs"].values():
        for step in job["steps"]:
            env_names |= set(step.get("env", {}))
    assert {"ELASTIC_URL", "ELASTIC_API_KEY", "KIBANA_URL"} <= env_names
    # Old Gmail-specific names were replaced by SMTP_* in validate_rule.py.
    assert not any(n.startswith("GMAIL_") for n in env_names)
    assert "SMTP_HOST" in env_names and "SF_REPO_URL" in env_names


