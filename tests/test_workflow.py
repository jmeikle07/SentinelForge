"""Static checks on the GitHub Actions workflows (offline, YAML only).

Shell behaviour of the scripts the workflow calls is tested in test_ci_changes.py.
"""
import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
WF_DIR = ROOT / ".github" / "workflows"
SCRIPTS = ROOT / "scripts"
DEPLOY = WF_DIR / "deploy-detections.yml"
TEST = WF_DIR / "test.yml"
SHA_RE = re.compile(r"^[^@\s]+@[0-9a-f]{40}$")
PLAN_STEP = "Find changed, removed and retagged Sigma rules"
PUSH_STEP = "Rebase and push healed rules"


def load(path):
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    # PyYAML (YAML 1.1) parses the bare key `on` as boolean True.
    if True in data and "on" not in data:
        data["on"] = data.pop(True)
    return data


def triggers(wf):
    on = wf["on"]
    return set(on) if isinstance(on, (dict, list)) else {on}


def all_steps(wf):
    for job_name, job in wf["jobs"].items():
        for step in job.get("steps", []):
            yield job_name, step


def run_scripts(wf):
    for job_name, step in all_steps(wf):
        if "run" in step:
            yield job_name, step["run"]


def script(name):
    return (SCRIPTS / name).read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def deploy():
    return load(DEPLOY)


@pytest.fixture(scope="module")
def testwf():
    return load(TEST)


def test_deploy_job_depends_on_validate_success(deploy):
    jobs = deploy["jobs"]
    assert "validate" in jobs and "deploy" in jobs
    needs = jobs["deploy"].get("needs")
    needs = [needs] if isinstance(needs, str) else needs
    assert "validate" in needs
    text = DEPLOY.read_text(encoding="utf-8")
    for bypass in ("cancelled()", "always()", "failure()", "continue-on-error"):
        assert bypass not in text, f"{bypass} would let deploy bypass validation"
    # Strict gating: no status-check function in any condition, so GitHub applies the implicit
    # success(): deploy is skipped unless every validate step (including the last one, which
    # fails the job when any rule failed) succeeded.
    conds = [str(j.get("if", "")) for j in jobs.values()]
    conds += [str(s.get("if", "")) for _, s in all_steps(deploy)]
    for c in conds:
        assert not re.search(r"\b(success|failure|always|cancelled)\(", c), c
    assert "needs.validate.outputs.has_work == 'true'" in str(jobs["deploy"]["if"])


def test_one_failing_rule_fails_the_job_only_after_healed_rules_are_published(deploy):
    steps = deploy["jobs"]["validate"]["steps"]
    idx = {}
    for key, needle in (("val", "ci_validate.sh"), ("heal", "ci_heal.sh"), ("push", "ci_push.sh")):
        idx[key] = next(i for i, s in enumerate(steps) if needle in s.get("run", ""))
    last = len(steps) - 1
    assert steps[last]["name"].startswith("Fail if any rule failed")
    assert idx["val"] < idx["heal"] < idx["push"] < last
    # validating never exits non-zero by itself; the final step does, once healing was published
    assert "exit 1" not in steps[idx["val"]]["run"]
    assert "failed.z" in steps[last]["run"] and "exit 1" in steps[last]["run"]
    assert "any_changed" in steps[last]["if"]
    assert "exit 0" in script("ci_validate.sh")
    assert "set -e" not in script("ci_validate.sh")


def test_test_workflow_uses_github_hosted_runner_on_pull_request(testwf):
    assert {"pull_request", "push"} <= triggers(testwf)
    for name, job in testwf["jobs"].items():
        assert job["runs-on"] == "ubuntu-latest", name
    assert "pull_request_target" not in TEST.read_text(encoding="utf-8")
    runs = "\n".join(s for _, s in run_scripts(testwf))
    assert "pytest" in runs
    # autogenerated rules are untagged until the deploy workflow's heal commit tags them,
    # so the strict check would turn every new rule's CI red
    assert "tools/tag_compliance.py --check --allow-untagged" in runs
    assert not re.search(r"tag_compliance\.py --check(?! --allow-untagged)", runs)
    assert "tools/readme_tables.py --check" in runs
    pys = [s["with"]["python-version"] for _, s in all_steps(testwf)
           if "with" in s and "python-version" in s["with"]]
    assert pys and all(str(p) == "3.12" for p in pys)


def test_pull_requests_never_run_on_self_hosted(deploy):
    assert "pull_request" not in triggers(deploy)
    assert "pull_request_target" not in triggers(deploy)
    assert triggers(deploy) == {"push"}
    assert deploy["on"]["push"]["branches"] == ["main"]
    for name, job in deploy["jobs"].items():
        assert "self-hosted" in str(job["runs-on"]), name
        assert "refs/heads/main" in str(job.get("if", "")), name
        assert "'push'" in str(job.get("if", "")), name


def test_no_secrets_exposed_to_pull_request_from_forks(deploy, testwf):
    # The test workflow has PR triggers: it must not touch any secret
    # beyond the implicit read-only GITHUB_TOKEN.
    text = TEST.read_text(encoding="utf-8")
    assert not re.findall(r"secrets\.(?!GITHUB_TOKEN)\w+", text)
    assert "secrets: inherit" not in text
    # Deploy workflow (which uses secrets) must not be PR-triggered at all.
    assert "pull_request" not in triggers(deploy)


def test_permissions_are_least_privilege(deploy, testwf):
    assert deploy["permissions"] == {}  # nothing by default
    # deploy only reads the repo (checkout); it never pushes.
    assert deploy["jobs"]["deploy"]["permissions"] == {"contents": "read"}
    # validate is the only job that pushes (the self-heal commit, scripts/ci_push.sh), which is
    # the sole reason for contents: write; actions: read lets tools/ci_changes.py ask the Actions
    # API for the last successful run.
    assert deploy["jobs"]["validate"]["permissions"] == {"contents": "write", "actions": "read"}
    assert testwf["permissions"] == {"contents": "read"}
    for wf in (deploy, testwf):
        for job in wf["jobs"].values():
            assert "pull-requests" not in job.get("permissions", {})
    pushers = {j for j, s in all_steps(deploy) if "ci_push.sh" in s.get("run", "")}
    assert pushers == {"validate"}
    assert "git push" not in "\n".join(s for _, s in run_scripts(deploy))


def test_write_token_is_not_persisted_and_only_reaches_plan_and_push_steps(deploy):
    for job_name, job in deploy["jobs"].items():
        for s in job["steps"]:
            if str(s.get("uses", "")).startswith("actions/checkout"):
                assert s["with"]["persist-credentials"] is False, job_name
    holders = [s["name"] for _, s in all_steps(deploy)
               if any("github.token" in str(v) or "GITHUB_TOKEN" in str(v)
                      for v in s.get("env", {}).values())]
    assert holders == [PLAN_STEP, PUSH_STEP]
    names = [s["name"] for s in deploy["jobs"]["validate"]["steps"]]
    assert names.index("Install dependencies") < names.index(PLAN_STEP)  # unpinned install runs first
    for _, s in all_steps(deploy):
        assert "set-url" not in s.get("run", "") and "x-access-token" not in s.get("run", "")
    push = script("ci_push.sh")
    assert "GIT_CONFIG_VALUE_0" in push and "http.extraheader" in push
    assert "remote set-url" not in push and "@github.com" not in push


