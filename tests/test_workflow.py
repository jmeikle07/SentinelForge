def test_concurrency_queues_runs_and_diff_base_is_last_success(deploy):
    assert deploy["concurrency"]["group"] == "deploy-detections"
    assert deploy["concurrency"]["cancel-in-progress"] is False
    # the one-pending-run limit and its mitigation are documented next to the config
    assert re.search(r"#.*ONE pending run", DEPLOY.read_text(encoding="utf-8"))
    validate_plan = next(s for j, s in all_steps(deploy) if j == "validate" and s.get("name") == PLAN_STEP)
    deploy_plan = next(s for j, s in all_steps(deploy) if j == "deploy" and s.get("name") == PLAN_STEP)
    # validate resolves the base (last successful run, else the push's before sha) ...
    assert "--event-before" in validate_plan["run"] and "--base-sha" not in validate_plan["run"]
    assert validate_plan["env"]["BEFORE_SHA"] == "${{ github.event.before }}"
    # ... and deploy reuses exactly that base, so it deploys what was validated
    assert "--base-sha" in deploy_plan["run"] and "--event-before" not in deploy_plan["run"]
    assert deploy_plan["env"]["BASE_SHA"] == "${{ needs.validate.outputs.base_sha }}"
    assert deploy["jobs"]["validate"]["outputs"]["base_sha"] == "${{ steps.plan.outputs.base_sha }}"


